// Compile a word list into a single case-insensitive regex: longest names first, any whitespace between words.
// Snowflake class instances are addressed by a dotted class name: SNOWFLAKE.CORE.BUDGET
const CLASS_NAME = "[sS][nN][oO][wW][fF][lL][aA][kK][eE]\\.[A-Za-z_][A-Za-z_0-9]*\\.[A-Za-z_][A-Za-z_0-9]*";

export function words_regex(list, with_class = false) {
  const uniq = [...new Set(list)].sort((a, b) => b.length - a.length);
  const alt = uniq.map(name =>
    name.split(" ").map(w => w.split("").map(c => `[${c.toLowerCase()}${c.toUpperCase()}]`.replace(/\[(\W)\W\]/, "$1")).join("")).join("\\s+")
  ).join("|");
  return new RegExp(with_class ? alt + "|" + CLASS_NAME : alt);
}
